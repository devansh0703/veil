const mintData = Buffer.from(mintInfo.value.data[0], 'base64');
/**
 * Walk the mint's TLV extension table.
 *
 * The base mint is 82 bytes; the account-type tag occupies byte 165, so the
 * extension header starts at 166. That off-by-one is the bug a previous version
 * of this project shipped — the reader started at 165 and read the account-type
 * byte as an extension type, which made a mint with the confidential extension
 * report as having none.
 */
const MINT_TLV_START = 166;
const extensionTypes: number[] = [];
{
  let cursor = MINT_TLV_START;
  while (cursor + 4 <= mintData.length) {
    const type = mintData.readUInt16LE(cursor);
    const length = mintData.readUInt16LE(cursor + 2);
    if (type === 0) break;
    extensionTypes.push(type);
    cursor += 4 + length;
  }
}
/**
 * `ConfidentialTransferMint` is extension type 4 in Token-2022's enum — this is
 * worth stating because 10 is `InterestBearingConfig`, and checking for 10 makes
 * a correctly-configured mint look unconfigured. `ConfidentialTransferAccount`,
 * the per-account counterpart, is 5.
 */
const EXT_CONFIDENTIAL_TRANSFER_MINT = 4;
if (!extensionTypes.includes(EXT_CONFIDENTIAL_TRANSFER_MINT)) {
  stop(
    'the mint does not carry the ConfidentialTransferMint extension',
    `extensions seen: ${extensionTypes.join(', ') || 'none'}`,
  );
  process.exit(1);
}
ok(
  'the mint carries the confidential extension',
  `type ${EXT_CONFIDENTIAL_TRANSFER_MINT} among [${extensionTypes.join(', ')}]`,
);

