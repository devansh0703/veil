if (!destinationExtension || destinationExtension.__kind !== 'ConfidentialTransferAccount') {
  stop('the destination has no ConfidentialTransferAccount extension', destination);
  process.exit(1);
}
if (!destinationExtension.allowConfidentialCredits) {
  stop('the destination does not accept confidential credits', destination);
  process.exit(1);
}
if (destinationExtension.allowNonConfidentialCredits) {
  // Not fatal, but worth naming: the pool is armed to *refuse* plain transfers,
  // which is what turns a failed proof into an on-chain error instead of a
  // silent public payment.
  process.stdout.write(
    `  note  the destination still accepts non-confidential credits; a failed\n` +
      `        proof would settle as a visible transfer on this account\n`,
  );
}
ok(
  'the destination accepts confidential credits',
  `allowNonConfidentialCredits=${destinationExtension.allowNonConfidentialCredits}`,
);

/**
 * The mint was created with `autoApproveNewAccounts: false`, which is the safer
 * setting — it means an account has to be vouched for by the mint authority
 * before it can hold a confidential balance, so a stranger cannot create one and
 * quietly receive private payments. The cost of that setting is that approval is
 * a *required* step, and an unapproved account fails `Deposit` and `Transfer`
 * with a bare `custom program error: 0x18` that names nothing useful. So it is
 * checked here and performed below rather than discovered from a program error.
 */
const destinationApproved = destinationExtension.approved;
if (destinationApproved) {
  ok('the destination is approved for confidential transfers');
} else {
  process.stdout.write(
    '  note  the destination is not yet approved for confidential transfers;\n' +
      '        the mint authority approves it before anything is deposited\n',
  );
}

