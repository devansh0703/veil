/**
 * Destinations this script has already paid into.
 *
 * Kept here rather than in the pool ledger on purpose. The ledger is the server's
 * record of *payments it quoted* — an alias, a reserved slot, a settlement — and
 * a script that reaches around the quote flow to stamp `consumedBy` on a slot
 * would be writing a reservation it never made. This file is go-live's own
 * bookkeeping: which pool accounts it has funded, and with what, so a re-run does
 * not try to spend into a destination that already holds a balance. That matters,
 * because the safety check below refuses a non-empty destination, and after the
 * first successful run *every* reused destination would trip it.
 */
const RUNS_PATH = join(DATA_DIR, `go-live${clusterTag(rpcUrl, options.network)}.json`);

interface GoLiveRuns {
  readonly runs: {
    readonly destination: string;
    readonly amount: string;
    readonly signature: string;
    readonly at: string;
  }[];
}

const priorRuns = await readJSON<GoLiveRuns>(RUNS_PATH, { runs: [] });
const funded = new Set(priorRuns.runs.map((run) => run.destination));

const destinationEntry = poolAccounts.find(
  (e) => e.armed && !e.consumedBy && !funded.has(e.address),
);
