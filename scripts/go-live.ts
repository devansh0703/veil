/**
 * scripts/go-live.ts — take the local build live, on chain.
 *
 *   npm run go:live                          # inspect only; nothing is broadcast
 *   npm run go:live -- --apply               # broadcast the real confidential transfer
 *
 * ## What "live" means here
 *
 * Everything else in this repository is verifiable without funds: the 402 body,
 * the refusal codes, the ledger arithmetic, the proofs. One claim is not, and it
 * is the load-bearing one — that a payment can move between two accounts with
 * the amount never appearing in the clear. That claim needs a chain.
 *
 * So this runs the smallest honest sequence that tests it:
 *
 *   0. Read the live state and refuse to proceed unless the preconditions are
 *      really there — the mint carries the confidential extension and the
 *      destination is armed. Broadcasting against an unverified mint is how you
 *      get a public transfer while believing it was private.
 *   1. Create a source account with the confidential extension already allocated,
 *      configure it with a pubkey-validity proof, and enable confidential
 *      credits. Non-confidential credits stay *enabled* on the source, because
 *      the next step needs to mint into it publicly; the destination is the
 *      account that refuses plain transfers.
 *   2. Mint public tokens into the source and deposit them. The deposit is what
 *      turns a visible balance into a spendable confidential one.
 *   3. Transfer to the destination using the three proofs generated by
 *      `packages/onchain/src/proofs.ts` — the same prover `npm test` exercises,
 *      not a second implementation written for this script.
 *   4. Apply the destination's pending balance, so the run ends with the money
 *      moved rather than parked in a state only the sender can see.
 *   5. Re-read the destination and decrypt locally, to *report* what actually
 *      landed instead of asserting it.
 *
 * ## Why the instructions come from Veil's builders
 *
 * The token-2022 SDK also ships `getConfidentialTransferInstructionPlan`, which
 * builds the transfer *and generates its own proofs*. Substituting Veil's proofs
 * into that plan would leave the SDK's proofs in place as well, and a transaction
 * carrying two sets of proof instructions is a transaction whose offsets no
 * longer mean what either producer intended. So this script uses the SDK only
 * for the two things Veil does not implement — the deposit instruction and the
 * account decoder — and builds the confidential sequence from
 * `packages/onchain/src/index.ts`, whose instruction order and proof offsets are
 * already covered by the test suite.
 *
 * ## Reading state back
 *
 * The SDK's `getTokenDecoder()` decodes the account including its extension
 * payload, and `decryptConfidentialTransferBalance` decrypts the balance
 * ciphertexts with the local keys. A hand-computed byte offset is exactly the
 * kind of thing that is right in a test fixture and wrong against live data.
 */

