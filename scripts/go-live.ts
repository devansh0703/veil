/**
 * The payer's confidential keys.
 *
 * Derived exactly as `setup-devnet` derives the pool's keys — one signature over
 * the fixed derivation message, reused across every account the payer owns. That
 * is not a shortcut: it is what makes step 4 possible at all. Applying the
 * destination's pending balance requires the *destination's* ElGamal secret, and
 * the pool's accounts share the payer's derivation, so the same keys decrypt
 * them. If the pool were configured with per-account keys, this script could not
 * finish the transfer it starts.
 */
async function signDerivation(seed: Uint8Array): Promise<Uint8Array> {
  const { createPrivateKey, sign } = await import('node:crypto');
  const PKCS8_ED25519_PREFIX = Buffer.from('302e020100300506032b657004220420', 'hex');
  const key = createPrivateKey({
    key: Buffer.concat([PKCS8_ED25519_PREFIX, Buffer.from(seed)]),
    format: 'der',
    type: 'pkcs8',
  });
  return new Uint8Array(sign(null, Buffer.from(confidentialDerivationMessage()), key));
}

let keys: ConfidentialKeys;
try {
  keys = await confidentialKeysFrom(() => signDerivation(payerSeed));
} catch (error) {
  stop('the confidential keys could not be derived', (error as Error).message);
  process.exit(1);
}
const sourceElgamalKeypair = keys.elgamal();
const aesKey = keys.ae();
ok('confidential keys derived locally', `ElGamal pubkey ${sourceElgamalKeypair.pubkey().toBytes().length}B`);

/**
 * The destination's ElGamal public key, read from its on-chain extension. The
 * stored form is base58 (it is an `Address`), so it is decoded to the 32 raw
 * bytes the prover takes.
 */
const destinationPubkey = ElGamalPubkey.fromBytes(
  new Uint8Array(getBase58Encoder().encode(destinationExtension.elgamalPubkey)),
);
ok('the destination ElGamal key decoded from live state', destinationExtension.elgamalPubkey);

// ---------------------------------------------------------------------------
// The source account, and what this run would cost
// ---------------------------------------------------------------------------

/**
 * A fresh source account per run.
 *
 * An associated token account will not do: a standard ATA is 165 bytes, and the
 * confidential extension needs the account to have been allocated with room for
 * it. Token-2022 can reallocate, but creating the account at the right size is
 * the shorter path and removes a whole class of "the extension was not there
 * yet" failures. The cost is one rent-exempt account, which is why this is
 * reported before it is spent.
 */
const source = await generateKeyPairSigner();
const sourceRent = await rpc
  .getMinimumBalanceForRentExemption(BigInt(confidentialAccountSpace()))
  .send();
const rentSol = Number(sourceRent) / 1e9;

if (!apply) {
  /**
   * Decrypt the destination here, before anything is spent.
   *
   * The final step of `--apply` depends on two things that are cheap to check
   * and expensive to discover late: that the SDK's decoder accepts this account
   * shape, and that the payer's derived keys are the ones the account was
   * configured with. If either is wrong, the run would broadcast a real transfer
   * and then be unable to read the result — the money would move and the script
   * would report a failure. So it is proven on the read-only path first.
   */
  const decrypted = decryptConfidentialTransferBalance({
    tokenAccount: decodedDestination,
    elgamalSecretKey: keys.elgamal().secret(),
    aesKey: keys.ae(),
  });
  ok(
    'the destination decrypts locally',
    `available ${decrypted.availableBalance}, pending ${decrypted.pendingBalance}, ` +
      `credits ${decrypted.actualPendingBalanceCreditCounter}/${decrypted.maximumPendingBalanceCreditCounter}`,
  );
  if (decrypted.availableBalance !== 0n || decrypted.pendingBalance !== 0n) {
    stop(
      'the destination is not empty',
      `available ${decrypted.availableBalance}, pending ${decrypted.pendingBalance} — ` +
        'this run assumes a fresh destination, and would overwrite a real balance',
    );
    process.exit(1);
  }

  process.stdout.write(
    [
      '',
      '  Read-only pass. Nothing was broadcast.',
      '',
      '  What --apply would do:',
      `    1. create + configure the source account ${source.address}`,
      `       ${confidentialAccountSpace()} B, ${rentSol.toFixed(6)} SOL rent`,
      '       with a pubkey-validity proof (generated here, from the local key)',
      `    2. approve the source${destinationApproved ? '' : ' and the destination'} —\n` +
      '       autoApproveNewAccounts is off, so the mint authority vouches for each',
      '    3. mint + deposit the amount public-side, then confidential-side:',
      `       0.049 tokens (${AMOUNT} atomic units) at ${options.decimals} decimals`,
      `    4. transfer ${AMOUNT} confidentially to ${destination}`,
      '       with 3 proofs from packages/onchain/src/proofs.ts',
      '    5. apply the pending balance on the destination',
      '    6. re-read and decrypt the destination, to report what landed',
      '',
      '  Every precondition above was read from the chain, not assumed.',
      '  Re-run with --apply to broadcast.',
      '',
    ].join('\n'),
  );
  process.exit(failed === 0 ? 0 : 1);
}

