/**
 * A gap between transactions.
 *
 * The free public RPC answers `429` under a burst, and this script sends eight
 * transactions in a row. Waiting is cheaper than retrying, and it makes the run
 * reproducible on the endpoint everyone has access to rather than only on a paid
 * one.
 */
const PAUSE_BETWEEN_TXS_MS = 1_200;

function step(n: string, title: string): void {
  process.stdout.write(`\n${n} · ${title}\n`);
}

function ok(label: string, detail = ''): void {
  process.stdout.write(`  ok    ${label}${detail ? `  ${detail}` : ''}\n`);
}

function stop(label: string, detail = ''): void {
  failed += 1;
  process.stdout.write(`  STOP  ${label}${detail ? `  ${detail}` : ''}\n`);
}

function sleep(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

/**
 * Retry an operation that only *reads* from the chain.
 *
 * This is deliberately not applied to broadcasting. A retried read is free and
 * idempotent; a retried send after an ambiguous failure is how a payment gets
 * made twice. So the split is: reads retry, sends are attempted once with their
 * own bounded retry around the *transport* only.
 */
async function retryRead<T>(label: string, fn: () => Promise<T>): Promise<T> {
  const MAX_ATTEMPTS = 5;
  let lastError: unknown = new Error(`${label} failed`);
  for (let attempt = 1; attempt <= MAX_ATTEMPTS; attempt++) {
    try {
      return await fn();
    } catch (error) {
      lastError = error;
      if (!isTransient(error) || attempt === MAX_ATTEMPTS) throw error;
      process.stdout.write(
        `  retry ${label} — attempt ${attempt + 1}/${MAX_ATTEMPTS}\n`,
      );
      await sleep(1_000 * 2 ** (attempt - 1) + Math.floor(Math.random() * 500));
    }
  }
  throw lastError;
}

/**
 * A rate-limited public RPC answers `429` and drops connections under load.
 * Those are worth retrying; a rejected instruction is not, and retrying it just
 * costs a second preflight failure.
 */
function isTransient(error: unknown): boolean {
  const text = String((error as { message?: string })?.message ?? error);
  return (
    text.includes('429') ||
    text.includes('Too Many Requests') ||
    text.includes('fetch failed') ||
    text.includes('ECONNRESET') ||
    text.includes('ETIMEDOUT') ||
    text.includes('socket hang up') ||
    text.includes('Blockhash not found')
  );
}

/**
 * Sign and send one transaction, then wait for it to be confirmed.
 *
 * Confirmation is not optional on this path: the next step reads the account the
 * previous step wrote, so a `sendTransaction` that has not landed yet would make
 * this script decrypt a balance that does not exist and report the wrong thing.
 * The signature is polled rather than subscribed because a public RPC's
 * websocket endpoint is the flakier of its two interfaces.
 */
async function send(label: string, instructions: readonly Instruction[]): Promise<string> {
  if (instructions.length === 0) throw new Error(`${label}: no instructions to send`);

  /**
   * Attempts are generous because the free public RPC enforces a per-second
   * request limit and this run sends eight transactions. Five attempts with a
   * one-second base ran out during development; the limiter clears in tens of
   * seconds, so the ceiling here is set to outlast it rather than to fail fast.
   */
  const MAX_SEND_ATTEMPTS = 8;
  let signature: string | undefined;
  let lastError: unknown = new Error('send failed');

  for (let attempt = 1; attempt <= MAX_SEND_ATTEMPTS; attempt++) {
    try {
      const { value: lifetime } = await rpc.getLatestBlockhash().send();
      const message = pipe(
        createTransactionMessage({ version: 0 }),
        (tx) => setTransactionMessageFeePayerSigner(payer, tx),
        (tx) => setTransactionMessageLifetimeUsingBlockhash(lifetime, tx),
        (tx) => appendTransactionMessageInstructions(instructions, tx),
      );
      const signed = await signTransactionMessageWithSigners(message);
      if (!isFullySignedTransaction(signed)) {
        throw new Error(`${label}: the transaction is not fully signed`);
      }
      signature = getSignatureFromTransaction(signed);
      await rpc
        .sendTransaction(getBase64EncodedWireTransaction(signed), {
          encoding: 'base64',
          preflightCommitment: 'confirmed',
        })
        .send();
      break;
    } catch (error) {
      lastError = error;
      if (!isTransient(error) || attempt === MAX_SEND_ATTEMPTS) throw error;
      const wait = Math.min(20_000, 2_000 * 2 ** (attempt - 1)) + Math.floor(Math.random() * 500);
      process.stdout.write(
        `  retry ${label} — attempt ${attempt + 1}/${MAX_SEND_ATTEMPTS} in ${Math.round(wait / 100) / 10}s\n`,
      );
      await sleep(wait);
    }
  }
  if (!signature) throw lastError;

  const CONFIRM_TIMEOUT_MS = 60_000;
  const deadline = Date.now() + CONFIRM_TIMEOUT_MS;
  while (Date.now() < deadline) {
    const { value } = await rpc
      .getSignatureStatuses([signature as never])
      .send();
    const status = value[0];
    if (status?.err) {
      throw new Error(`${label}: the transaction failed on chain — ${JSON.stringify(status.err)}`);
    }
    if (status?.confirmationStatus === 'confirmed' || status?.confirmationStatus === 'finalized') {
      ok(label, `${instructions.length} ix · ${signature}`);
      return signature;
    }
    // Polled slowly on purpose: each poll is a request against the same
    // per-second budget as the transactions themselves, so a tight poll loop
    // starves the next send. Confirmation normally lands inside one interval.
    await sleep(2_000);
  }
  throw new Error(`${label}: ${signature} was not confirmed within ${CONFIRM_TIMEOUT_MS / 1000}s`);
}

