step('2', 'Create and configure the source account');

/**
 * Order matters, and it is the order `setup-devnet` proved against the live
 * program: allocate the account, then the pubkey-validity proof, then the
 * configure instruction that refers to it by offset, then enable confidential
 * credits.
 *
 * `disableNonConfidentialCredits` is deliberately omitted. The destination in
 * this pool refuses plain credits; the source must accept them, because the next
 * step mints into it publicly before depositing.
 */
await send('created + configured the source, with a local pubkey proof', [
  ...buildCreatePaymentAccount({
    payer,
    account: source,
    mint,
    owner: payer.address,
    lamports: sourceRent,
  }),
  buildPubkeyValidityProof(keys),
  buildConfigureAccount({
    token: source.address,
    mint,
    authority: payer,
    proofInstructionOffset: PROOF_OFFSET_IMMEDIATELY_PRECEDING,
    maximumPendingBalanceCreditCounter: MAX_PENDING_CREDIT_COUNTER,
    decryptableZeroBalance: encryptBalance(keys, 0n),
  }),
  getEnableConfidentialCreditsInstruction({ token: source.address, authority: payer }),
  // The mint authority vouches for this account. Without it the deposit below
  // fails, because `autoApproveNewAccounts` is false on this mint.
  getApproveConfidentialTransferAccountInstruction({
    token: source.address,
    mint,
    authority: payer,
  }),
]);

if (!destinationApproved) {
  await send('approved the destination for confidential transfers', [
    getApproveConfidentialTransferAccountInstruction({
      token: destination,
      mint,
      authority: payer,
    }),
  ]);
}

// ---------------------------------------------------------------------------
// 3 · Fund it publicly, then deposit
// ---------------------------------------------------------------------------

step('3', 'Mint public tokens, then deposit them');

await send('minted the amount publicly', [
  getMintToInstruction({
    mint,
    token: source.address,
    mintAuthority: payer,
    amount: AMOUNT,
  }),
]);

// The deposit is the step that turns a visible balance into a confidential one.
// A plain amount goes in; the account's encrypted balance becomes that amount.
await send('deposited into the confidential balance', [
  getConfidentialDepositInstruction({
    token: source.address,
    mint,
    authority: payer,
    amount: AMOUNT,
    decimals: options.decimals,
  }),
]);

/**
 * Move the deposit from pending to available.
 *
 * A deposit credits the *pending* balance, not the available one. Token-2022
 * separates the two on purpose: value that arrived while the owner was not
 * looking cannot be spent until the owner has acknowledged it. So an account can
 * hold 0.049 tokens, decrypt them, and still have nothing spendable — which is
 * exactly what the first run of this script discovered, one step later, with an
 * available balance of zero and a pending balance of 49000.
 */
const depositedInfo = await rpc.getAccountInfo(source.address, { encoding: 'base64' }).send();
if (!depositedInfo.value) throw new Error('the source account vanished after the deposit');
const depositedBalance = decryptConfidentialTransferBalance({
  tokenAccount: tokenDecoder.decode(Buffer.from(depositedInfo.value.data[0], 'base64')),
  elgamalSecretKey: sourceElgamalKeypair.secret(),
  aesKey,
});
ok(
  'the deposit landed in the pending balance',
  `pending ${depositedBalance.pendingBalance}, available ${depositedBalance.availableBalance}`,
);

await send('applied the deposit to the available balance', [
  buildApplyPendingBalance({
    token: source.address,
    authority: payer,
    expectedPendingBalanceCreditCounter: depositedBalance.expectedPendingBalanceCreditCounter,
    newDecryptableAvailableBalance: encryptBalance(
      keys,
      depositedBalance.availableBalance + depositedBalance.pendingBalance,
    ),
  }),
]);

// ---------------------------------------------------------------------------
// 4 · The confidential transfer, proved by Veil
// ---------------------------------------------------------------------------

step('4', "Transfer confidentially, with Veil's proofs generated locally");

const armedSource = await rpc.getAccountInfo(source.address, { encoding: 'base64' }).send();
if (!armedSource.value) throw new Error('the source account vanished after the deposit');
const decodedSource = tokenDecoder.decode(Buffer.from(armedSource.value.data[0], 'base64'));
const sourceExtensions = isSome(decodedSource.extensions) ? decodedSource.extensions.value : [];
const sourceExtension = sourceExtensions.find(
  (e) => e.__kind === 'ConfidentialTransferAccount',
);
if (!sourceExtension || sourceExtension.__kind !== 'ConfidentialTransferAccount') {
  throw new Error('the source lost its confidential extension after the deposit');
}

// Decrypt locally, so the amount moved is a number this run knows rather than
// one it assumed. The ciphertext is public — it is on the account — but the
// plaintext behind it exists only here.
const sourceBefore = decryptConfidentialTransferBalance({
  tokenAccount: decodedSource,
  elgamalSecretKey: sourceElgamalKeypair.secret(),
  aesKey,
});
ok(
  'the source balance was decrypted locally',
  `available ${sourceBefore.availableBalance}, pending ${sourceBefore.pendingBalance}`,
);

if (sourceBefore.availableBalance !== AMOUNT) {
  // The equality proof commits to "new balance = the on-chain balance minus this
  // transfer". Proving against a balance the chain does not hold fails, so this
  // is checked rather than assumed — a deposit that silently deposited a
  // different amount would otherwise surface as an opaque program error.
  throw new Error(
    `the source available balance is ${sourceBefore.availableBalance}, expected ${AMOUNT}; ` +
      'the equality proof would commit to the wrong value',
  );
}

// The 64-byte commitment||handle the prover takes, straight from the decoded
// extension — no byte-offset arithmetic.
const balanceCiphertext = new Uint8Array(sourceExtension.availableBalance);
const parsedBalance = ElGamalCiphertext.fromBytes(balanceCiphertext);
if (!parsedBalance) {
  throw new Error(
    `the decoded available balance is not a valid ElGamal ciphertext (${balanceCiphertext.length} bytes)`,
  );
}
ok('the on-chain ciphertext was decoded from live state', `${balanceCiphertext.length}B`);

const proofs = buildTransferProofs({
  keys,
  sourceAvailableBalance: sourceBefore.availableBalance,
  sourceAvailableBalanceCiphertext: parsedBalance,
  amount: AMOUNT,
  destinationPubkey,
});

const proofBytes = proofs.proofBytes;
const proofTotal = proofBytes.equality.length + proofBytes.ciphertextValidity.length + proofBytes.range.length;
ok(
  'three proofs generated locally',
  `${proofBytes.equality.length} + ${proofBytes.ciphertextValidity.length} + ` +
    `${proofBytes.range.length} = ${proofTotal} B`,
);
ok(
  'the new source balance is the old one minus the amount',
  `${sourceBefore.availableBalance} − ${AMOUNT} = ${proofs.newAvailableBalance}`,
);

/**
 * Verify the proofs into context-state accounts, then transfer against them.
 *
 * This is the shape the arithmetic forces. 1867 bytes of proof do not fit in a
 * 1232-byte transaction, and the offset form of the transfer requires all three
 * verification instructions to be *in the same transaction* — so a transfer of
 * this size can never work that way. Verifying into context-state accounts moves
 * the proofs out of the transfer's transaction entirely; the transfer then names
 * three accounts and sets every offset to `0`, the wire value for "read the
 * proof from the account".
 */
const recordKeys = {
  equality: await generateKeyPairSigner(),
  ciphertextValidity: await generateKeyPairSigner(),
  range: await generateKeyPairSigner(),
};

/**
 * Each proof gets its own transaction.
 *
 * The largest payload is 1001 bytes and each verification carries an account
 * creation and a rent check, so combining them would put the transaction back
 * over the ceiling that made this necessary.
 */
/**
 * Verify one proof into a context account, retrying only the read-only build.
 *
 * The SDK's verify action queries the chain for the context account's rent before
 * it can build the instructions, and that read is what a public RPC's rate
 * limiter hits first. The query is retried; the send is not wrapped in the same
 * loop, because re-running it after an ambiguous failure would try to create the
 * same context account a second time.
 */
async function verifyIntoContext(
  label: string,
  verify: typeof verifyBatchedRangeProofU128,
  contextAccount: Awaited<ReturnType<typeof generateKeyPairSigner>>,
  proofData: Parameters<typeof verifyBatchedRangeProofU128>[0]['proofData'],
): Promise<void> {
  const instructions = await retryRead(`build the verification for ${label}`, () =>
    verify({
      rpc,
      payer,
      proofData,
      contextState: { contextAccount, authority: payer.address },
    }),
  );
  await send(label, instructions);
  await sleep(PAUSE_BETWEEN_TXS_MS);
}

await verifyIntoContext(
  'verified the equality proof into a context account',
  verifyCiphertextCommitmentEquality,
  recordKeys.equality,
  proofBytes.equality,
);

await verifyIntoContext(
  'verified the ciphertext-validity proof into a context account',
  verifyBatchedGroupedCiphertext3HandlesValidity,
  recordKeys.ciphertextValidity,
  proofBytes.ciphertextValidity,
);

/**
 * The range proof is the one that does not fit — in anything.
 *
 * It is 1000 bytes. Embedded as instruction data, its verification transaction
 * comes to 1816 bytes against the same 1232-byte ceiling, so unlike the other two
 * it cannot be carried inline even in a transaction of its own. Token-2022's
 * answer is a *record account*: the proof is written into an account of its own,
 * a chunk per transaction, and the verification instruction then names that
 * account instead of embedding the bytes. The transaction shrinks to a few
 * hundred bytes because account data does not count against a transaction's size
 * — only the account's 32-byte address does.
 *
 * This is the same mechanism the SDK's `...WithRecord` helpers use. It is built
 * by hand here rather than delegated, because the whole point of this script is
 * that the proof bytes are Veil's.
 */
const rangeRecord = await generateKeyPairSigner();
const rangeRecordSize = getRecordSize(proofBytes.range.length);
const rangeRecordRent = await retryRead('read the record account rent', () =>
  rpc.getMinimumBalanceForRentExemption(rangeRecordSize).send(),
);

await send(`created a ${rangeRecordSize}B record account for the range proof`, [
  getCreateAccountInstruction({
    payer,
    newAccount: rangeRecord,
    lamports: rangeRecordRent,
    space: rangeRecordSize,
    programAddress: RECORD_PROGRAM_ADDRESS,
  }),
  getInitializeRecordInstruction({ recordAccount: rangeRecord.address, authority: payer }),
]);
await sleep(PAUSE_BETWEEN_TXS_MS);

// One chunk per transaction: a full 917-byte chunk plus another instruction would
// put the transaction back over the limit, which is why the chunk size is what it
// is.
const chunks: Uint8Array[] = [];
for (let offset = 0; offset < proofBytes.range.length; offset += RECORD_CHUNK_SIZE_POST_INITIALIZE) {
  chunks.push(proofBytes.range.slice(offset, offset + RECORD_CHUNK_SIZE_POST_INITIALIZE));
}
for (const [index, chunk] of chunks.entries()) {
  const offset = index * RECORD_CHUNK_SIZE_POST_INITIALIZE;
  await send(
    `wrote range-proof bytes ${offset}..${offset + chunk.length} into the record account`,
    [
      getWriteInstruction({
        recordAccount: rangeRecord.address,
        authority: payer,
        offset,
        data: chunk,
      }),
    ],
  );
  await sleep(PAUSE_BETWEEN_TXS_MS);
}

// The offset is `RECORD_META_DATA_SIZE` (33) and not 0, because a record account
// carries a 33-byte header and the proof payload begins after it. `Write`'s own
// offset is payload-relative and the program adds the header itself, which is why
// the writes above start at 0 while this read starts at 33 — an asymmetry worth
// naming, because reading at 0 fails with `proof verification failed:
// ProofContext`, which names neither the offset nor the record.
await verifyIntoContext(
  'verified the range proof into a context account, reading it from the record',
  verifyBatchedRangeProofU128,
  recordKeys.range,
  // `RECORD_META_DATA_SIZE` is a bigint and the proof-data argument takes a
  // number, so it is converted — the same conversion the SDK's own record path
  // performs. 33 bytes cannot lose precision going through a number.
  { account: rangeRecord.address, offset: Number(RECORD_META_DATA_SIZE) },
);

// The record account is scaffolding too, and it is the largest of the temporary
// accounts. Closing it returns its rent to the payer.
await send('closed the record account', [
  getCloseRecordAccountInstruction({
    recordAccount: rangeRecord.address,
    authority: payer,
    receiver: payer.address,
  }),
]);
await sleep(PAUSE_BETWEEN_TXS_MS);

const transferSignature = await send('transferred confidentially', [
  ...buildConfidentialTransfer({
    sourceToken: source.address,
    mint,
    destinationToken: destination,
    authority: payer,
    newSourceDecryptableAvailableBalance: proofs.newSourceDecryptableAvailableBalance,
    transferAmountAuditorCiphertextLo: proofs.auditorCiphertextLo,
    transferAmountAuditorCiphertextHi: proofs.auditorCiphertextHi,
    proofRecords: {
      equality: recordKeys.equality.address,
      ciphertextValidity: recordKeys.ciphertextValidity.address,
      range: recordKeys.range.address,
    },
  }),
]);

/**
 * Reclaim the context accounts' rent.
 *
 * They are scaffolding: a proof is verified into one so a *later* transaction can
 * refer to it, and once the transfer has read it the account has no further use.
 * Leaving them behind would leak a rent-exempt balance per payment, which on a
 * real rail is a slow leak proportional to volume. Closing is also what proves
 * the accounts really were plain context state rather than something the transfer
 * still depended on.
 */
await send('closed the three context accounts', [
  closeContextStateProof({
    contextState: recordKeys.equality.address,
    authority: payer,
    destination: payer.address,
  }),
  closeContextStateProof({
    contextState: recordKeys.ciphertextValidity.address,
    authority: payer,
    destination: payer.address,
  }),
  closeContextStateProof({
    contextState: recordKeys.range.address,
    authority: payer,
    destination: payer.address,
  }),
]);

// ---------------------------------------------------------------------------
// 5 · Apply the destination's pending balance
// ---------------------------------------------------------------------------

step('5', 'Apply the pending balance on the destination');

const creditedInfo = await rpc.getAccountInfo(destination, { encoding: 'base64' }).send();
if (!creditedInfo.value) throw new Error('the destination vanished after the transfer');
const decodedCredited = tokenDecoder.decode(Buffer.from(creditedInfo.value.data[0], 'base64'));

const destinationBefore = decryptConfidentialTransferBalance({
  tokenAccount: decodedCredited,
  elgamalSecretKey: sourceElgamalKeypair.secret(),
  aesKey,
});
ok(
  'the destination received a pending credit',
  `pending ${destinationBefore.pendingBalance}, available ${destinationBefore.availableBalance}`,
);
if (destinationBefore.pendingBalance !== AMOUNT) {
  throw new Error(
    `the destination pending balance is ${destinationBefore.pendingBalance}, expected ${AMOUNT}`,
  );
}

const newAvailable = destinationBefore.availableBalance + destinationBefore.pendingBalance;
await send('applied the pending balance', [
  buildApplyPendingBalance({
    token: destination,
    authority: payer,
    expectedPendingBalanceCreditCounter: destinationBefore.expectedPendingBalanceCreditCounter,
    newDecryptableAvailableBalance: encryptBalance(keys, newAvailable),
  }),
]);

// ---------------------------------------------------------------------------
// 6 · Report what actually landed
// ---------------------------------------------------------------------------

step('6', 'Read the result back and decrypt it locally');

const finalInfo = await rpc.getAccountInfo(destination, { encoding: 'base64' }).send();
if (!finalInfo.value) throw new Error('the destination vanished after the apply');
const decodedFinal = tokenDecoder.decode(Buffer.from(finalInfo.value.data[0], 'base64'));
const destinationAfter = decryptConfidentialTransferBalance({
  tokenAccount: decodedFinal,
  elgamalSecretKey: sourceElgamalKeypair.secret(),
  aesKey,
});

if (destinationAfter.availableBalance !== newAvailable || destinationAfter.pendingBalance !== 0n) {
  stop(
    'the destination did not settle as expected',
    `available ${destinationAfter.availableBalance}, pending ${destinationAfter.pendingBalance}`,
  );
} else {
  ok(
    'the destination settled',
    `available ${destinationAfter.availableBalance}, pending ${destinationAfter.pendingBalance}`,
  );
}

if (failed === 0) {
  // Recorded only on a clean run, so a partial attempt does not claim a
  // destination it never funded.
  await saveJSON(RUNS_PATH, {
    runs: [
      ...priorRuns.runs,
      {
        destination: String(destination),
        amount: String(AMOUNT),
        signature: transferSignature,
        at: new Date().toISOString(),
      },
    ],
  } satisfies GoLiveRuns);
  ok('the run was recorded', relative(RUNS_PATH));
}

// The explorer wants a cluster *name*; the offer carries a CAIP-2 genesis hash.
// The endpoint this run actually used is the least ambiguous way to recover it.
const explorerCluster = /devnet|testnet|mainnet/.test(rpcUrl)
  ? rpcUrl.includes('devnet')
    ? 'devnet'
    : rpcUrl.includes('testnet')
      ? 'testnet'
      : 'mainnet-beta'
  : options.network.includes('devnet')
    ? 'devnet'
    : options.network.includes('testnet')
      ? 'testnet'
      : 'mainnet-beta';

process.stdout.write(
  [
    '',
    'Veil — live on chain',
    '',
    table([
      ['mint', String(mint)],
      ['payer', String(payer.address)],
      ['source', String(source.address)],
      ['destination', String(destination)],
      ['amount', `${AMOUNT} atomic units, never in the clear`],
      ['proofs', '3 per transfer, generated locally'],
      ['landed', `${destinationAfter.availableBalance} atomic units, decrypted locally`],
    ]),
    '',
    'The amount moved between two accounts without appearing in the clear.',
    'The only place it was ever legible was this process, which held the keys.',
    '',
    failed === 0
      ? `Look it up: https://explorer.solana.com/address/${destination}?cluster=${explorerCluster}`
      : `${failed} check(s) failed.`,
    '',
  ].join('\n'),
);

process.exit(failed === 0 ? 0 : 1);
